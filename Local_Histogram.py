import cv2
import numpy as np

def LocalHistogramStatistics(img, k0=0.4, k1=0.02, k2=0.4, C=5.0, window_size=3):
    """
    بهسازی تصویر با استفاده از آماره‌های محلی (سوال ۵ - منطبق بر الگوریتم شکل ۳.27 کتاب گونزالز)
    
    پارامترها:
    - k0: ضریب آستانه برای بررسی تاریک بودن میانگین محلی نسبت به میانگین کل
    - k1, k2: ضرایب بازه پذیرش انحراف معیار محلی (سنجش میزان کم‌کنتراست بودن همسایگی)
    - C: ضریب تقویت پیکسل‌هایی که شروط بهسازی را برآورده می‌کنند
    - window_size: ابعاد پنجره لغزان همسایگی (مثلاً 3 برای پنجره 3x3)
    """
    # ۱. محاسبه آماره‌های سراسری (Global) تصویر ورودی
    m_G = np.mean(img)      # میانگین کل تصویر
    sigma_G = np.std(img)    # انحراف معیار کل تصویر
    
    h, w = img.shape
    pad = window_size // 2
    
    # ۲. اعمال پدینگ انعکاسی روی لبه‌ها برای جلوگیری از کوچک شدن تصویر حین فیلترینگ
    padded_img = np.pad(img, pad, mode='reflect').astype(np.float32)
    out_img = img.copy().astype(np.float32)
    
    # ۳. پیمایش پیکسل به پیکسل تصویر با پنجره لغزان
    for i in range(h):
        for j in range(w):
            # استخراج ماتریس همسایگی محلی (پنجره)
            window = padded_img[i : i + window_size, j : j + window_size]
            
            # ۴. محاسبه آماره‌های محلی (Local) درون پنجره
            m_S = np.mean(window)       # میانگین محلی
            sigma_S = np.std(window)     # انحراف معیار محلی
            
            # ۵. بررسی دقیق شروط سه‌گانه گونزالز:
            # شرط اول: میانگین محلی تاریک‌تر از حد مجاز باشد (m_S <= k0 * m_G)
            # شرط دوم: انحراف معیار محلی در بازه کنتراست پایین قرار داشته باشد (k1 * sigma_G <= sigma_S <= k2 * sigma_G)
            if (m_S <= k0 * m_G) and (k1 * sigma_G <= sigma_S <= k2 * sigma_G):
                # تقویت پیکسل واجد شرایط با ضرب در ضریب C
                out_img[i, j] = C * img[i, j]
                
    # ۶. محدود کردن مقادیر بین 0 و 255 و تبدیل مجدد به تیپ داده استاندارد تصویری uint8
    return np.clip(out_img, 0, 255).astype(np.uint8)